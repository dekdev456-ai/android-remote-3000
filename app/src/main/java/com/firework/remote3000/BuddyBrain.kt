    fun onTap(): String = tapReactions.random()

    fun nextFunTopic(): String {
        activeRiddle = null
        return funTopics.random()
    }

    fun playRps(userMove: String? = null): String {
        val moves = listOf("ค้อน ✊", "กรรไกร ✌️", "กระดาษ ✋")
        val bot = moves.random()
        if (userMove == null) {
            return "มาเลย! น้องพลุพร้อมแล้ว พิมพ์หรือพูด 'ค้อน', 'กรรไกร' หรือ 'กระดาษ' มาเลย!"
        }
        val uIdx = when {
            userMove.contains("ค้อน") -> 0
            userMove.contains("กรรไกร") -> 1
            userMove.contains("กระดาษ") -> 2
            else -> return "เลือก 'ค้อน', 'กรรไกร' หรือ 'กระดาษ' นะคู่หู!"
        }
        val bIdx = moves.indexOf(bot)
        val result = when {
            uIdx == bIdx -> "เสมอเลย! ใจตรงกันนะเนี่ย 😄"
            (uIdx == 0 && bIdx == 1) || (uIdx == 1 && bIdx == 2) || (uIdx == 2 && bIdx == 0) -> "เย้! คุณชนะ! เก่งมาก 🎉"
            else -> "ฮ่า ๆ น้องพลุชนะตานี้! เอาอีกตาไหม? ✨"
        }
        return "คุณออก ${moves[uIdx]} vs น้องพลุออก $bot → $result"
    }

    fun reply(rawInput: String): String {
        val text = rawInput.trim()
        if (text.isEmpty()) return nextFunTopic()
        val low = text.lowercase()

        // Check active riddle answer
        activeRiddle?.let { r ->
            if (low.contains("เฉลย") || low.contains("ยอมแพ้") || low.contains("ไม่รู้")) {
                activeRiddle = null
                return "เฉลยคือ '${r.answerHint}' ไงล่ะ! ฮ่า ๆ ลองข้อใหม่ไหม?"
            }
            if (r.keywords.any { low.contains(it) }) {
                activeRiddle = null
                return "🎉 ถูกต้อง!! เก่งสุด ๆ คำตอบคือ '${r.answerHint}' เอง! อยากเล่นอีกข้อไหม?"
            }
        }

        return when {
            low.contains("ค้อน") || low.contains("กรรไกร") || low.contains("กระดาษ") -> playRps(low)
            low.contains("เป่ายิ้งฉุบ") || low.contains("เล่นเกม") -> playRps(null)
            low.contains("ทายปัญหา") || low.contains("คำถาม") -> {
                val r = riddles.random()
                activeRiddle = r
                "${r.question} (พิมพ์/พูดคำตอบ หรือพูดว่า 'เฉลย' ได้เลย!)"
            }
            low.contains("มุก") || low.contains("ตลก") || low.contains("ขำ") -> jokes.random()
            low.contains("กี่โมง") || low.contains("เวลา") -> {
                val now = SimpleDateFormat("HH:mm น.", Locale.getDefault()).format(Date())
                "⏰ ตอนนี้เวลา $now แล้วครับ อย่าลืมพักสายตาและดื่มน้ำด้วยนะ!"
            }
            low.contains("สวัสดี") || low.contains("หวัดดี") || low.contains("ดีจ้า") || low.contains("hi") || low.contains("hello") ->
                "สวัสดีคู่หู! ✨ น้องพลุพร้อมอยู่เป็นเพื่อนแล้ว วันนี้มีเรื่องดี ๆ อะไรมาเล่าให้ฟังไหม หรืออยากให้น้องหาเรื่องสนุก ๆ คุยให้?"
            low.contains("ชื่ออะไร") || low.contains("ใคร") ->
                "ผมชื่อ 'น้องพลุ (Pyro Buddy)' ✨ คู่หูประจำเครื่องของคุณ! ชอบหาเรื่องสนุก ๆ เกร็ดความรู้ มุกตลก และเป็นเพื่อนคุยตอนคุณทำโปรเจกต์ครับ!"
            low.contains("เหนื่อย") || low.contains("เครียด") || low.contains("ท้อ") ->
                "กอด ๆ นะคู่หู 💛 พักหายใจลึก ๆ สัก 5 วินาทีก่อนก็ได้นะ คุณเก่งมากที่พยายามมาถึงขนาดนี้ เดี๋ยวน้องพลุเล่าเรื่องสนุก ๆ ให้ฟังไหม?"
            low.contains("เบื่อ") || low.contains("เหงา") ->
                "อย่าเพิ่งเบื่อเลย! มาเล่นเป่ายิ้งฉุบ หรือทายปัญหากับน้องพลุดีกว่า หรือกดปุ่ม 🎲 หาเรื่องคุย เดี๋ยวน้องจัดให้!"
            low.contains("ง่วง") ->
